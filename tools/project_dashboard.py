"""Dashboard status publishing for `kit.py project dashboard|status` (T23 Part B).

Used by tools/projects.py only. The host configuration (`<kit>/.ai-factory-state/dashboard.json`,
0600) holds paths only: the dashboard Go module, its projects config and its private feed.
`project status` takes an agent's status JSON on stdin, adds schema, project, the project's
current HEAD and the observation time, and hands it to the dashboard's own publisher
(`go run . -publish [-apply]`), whose checks stay the only gate. It never prints record text.
"""
import datetime
import json
import os
import re
from pathlib import Path
import shutil
import stat
import subprocess
import unicodedata

CONFIG = 'dashboard.json'
SCHEMA = 'factory-dashboard/status/1'
MAX_INPUT = 16 * 1024
AGENT_FIELDS = {'taskId', 'title', 'state', 'next', 'sources', 'stages', 'markdown'}
FILLED = {'schema', 'project', 'revision', 'updatedAt'}
TIMEOUT = 180


class Blocked(ValueError):
    pass


GENERATED = 'dashboard-projects.json'
# The dashboard's own rules (runtime/dashboard/projects.go newRegistry/validRoot, feed.go textOK/address/slug),
# ported so the kit never writes a projects file the dashboard rejects. A test checks parity with the Go validator.
ADDRESS = re.compile(r'(?i)(://|file:|~[/\\]|(?:^|[\s(`"\'])[/\\]|[a-z]:\\|\.\.[/\\])')
PROJECT_ID = re.compile(r'[a-z0-9][a-z0-9-]{0,62}')
TASK_SLUG = re.compile(r'[a-z0-9][a-z0-9-]{0,47}')
MAX_PROJECTS, MAX_ALIASES, MAX_ROOT = 32, 8, 1024
CAPABILITY_KEYS = {'id', 'name', 'workflow', 'aliases'}


def text_ok(value, limit):
    if not isinstance(value, str) or not value.strip(): return False
    try:
        raw = value.encode('utf-8')
    except UnicodeEncodeError:
        return False
    if len(raw) > limit or ADDRESS.search(value): return False
    return not any(unicodedata.category(c) == 'Cc' for c in value)


def valid_root(root):
    if not isinstance(root, str) or not root or len(root.encode('utf-8', 'surrogatepass')) > MAX_ROOT: return False
    if (not root.startswith('/') or root.startswith('//') or os.path.normpath(root) != root or root == '/'
            or ',' in root or '"' in root): return False
    return not any(unicodedata.category(c) == 'Cc' for c in root)


def check_capabilities(entries):
    """entries: [(root, capability)] in list order. Raises Blocked with the dashboard's reason."""
    if len(entries) > MAX_PROJECTS: raise Blocked(f'at most {MAX_PROJECTS} projects can be on the dashboard')
    ids = set()
    for root, cap in entries:
        if not isinstance(cap, dict) or not {'id', 'name'} <= set(cap) <= CAPABILITY_KEYS:
            raise Blocked('invalid dashboard capability')
        if not isinstance(cap['id'], str) or not PROJECT_ID.fullmatch(cap['id']) or cap['id'] in ids:
            raise Blocked('invalid or duplicate dashboard id')
        ids.add(cap['id'])
        if not text_ok(cap['name'], 80): raise Blocked(f"invalid dashboard name for {cap['id']}")
        if not valid_root(root):
            raise Blocked(f"project root of {cap['id']} must be a clean absolute path without commas, quotes or control characters")
        if 'workflow' in cap and not text_ok(cap['workflow'], 560): raise Blocked(f"invalid workflow note for {cap['id']}")
        aliases = cap.get('aliases', [])
        if 'aliases' in cap and (not isinstance(aliases, list) or not aliases):
            raise Blocked(f"invalid aliases for {cap['id']}")
        if len(aliases) > MAX_ALIASES: raise Blocked(f"too many aliases for {cap['id']}")
    for _, cap in entries:
        for a in cap.get('aliases', []):
            if (not isinstance(a, dict) or set(a) != {'id', 'task'} or not isinstance(a['id'], str)
                    or not PROJECT_ID.fullmatch(a['id']) or a['id'] in ids
                    or not isinstance(a['task'], str) or not TASK_SLUG.fullmatch(a['task'])):
                raise Blocked('invalid or duplicate dashboard alias')
            ids.add(a['id'])


def rows(entries):
    out = []
    for root, cap in entries:
        row = {'id': cap['id'], 'name': cap['name'], 'root': root}
        if 'workflow' in cap: row['workflow'] = cap['workflow']
        if cap.get('aliases'): row['aliases'] = [{'id': a['id'], 'task': a['task']} for a in cap['aliases']]
        out.append(row)
    return out


def generated_bytes(entries):
    """The dashboard projects file for these capable entries, or None when there are none."""
    if not entries: return None
    check_capabilities(entries)
    return (json.dumps(rows(entries), indent=1, ensure_ascii=False) + '\n').encode('utf-8')


def go_validate(cfg, data):
    """Run the dashboard's own validator on generated bytes (needs the configured Go and source)."""
    import tempfile
    with tempfile.TemporaryDirectory() as d:
        path = Path(d) / 'projects.json'
        path.write_bytes(data)
        r = subprocess.run([cfg['go'], 'run', '-tags', 'nobundle', '.', '-projects', str(path), '-list-projects'],
                           cwd=cfg['source'], capture_output=True, timeout=TIMEOUT, env=go_env())
    if r.returncode != 0: raise Blocked('the dashboard rejected the generated projects file: ' + last_line(r.stderr.decode('utf-8', 'replace')))


def canonical(value, label):
    p = Path(value)
    if not p.is_absolute() or os.path.normpath(value) != value or str(p.resolve()) != value:
        raise Blocked(f'{label} must be an absolute canonical path')
    return p


def go_binary(value=None):
    path = value or shutil.which('go') or ('/usr/local/go/bin/go' if os.access('/usr/local/go/bin/go', os.X_OK) else None)
    if not path or not Path(path).is_absolute() or not os.access(path, os.X_OK):
        raise Blocked('Go is required: pass --go with an absolute go executable')
    return path


def check_config(cfg):
    if not isinstance(cfg, dict) or set(cfg) != {'schema', 'source', 'projects', 'feed', 'go'} or cfg['schema'] != 1:
        raise Blocked('invalid dashboard configuration')
    source = canonical(cfg['source'], 'dashboard source')
    if not (source / 'go.mod').is_file() or b'module factory-dashboard' not in (source / 'go.mod').read_bytes():
        raise Blocked('dashboard source must be the factory-dashboard Go module (runtime/dashboard)')
    if not canonical(cfg['projects'], 'projects config').is_file():
        raise Blocked('projects config is missing')
    feed = canonical(cfg['feed'], 'feed directory')
    s = feed.stat() if feed.is_dir() and not feed.is_symlink() else None
    if s is None or s.st_uid != os.getuid() or stat.S_IMODE(s.st_mode) & 0o077:
        raise Blocked('feed must be an existing private (0700) directory owned by you')
    go_binary(cfg['go'])
    return cfg


def build_config(args):
    return check_config({'schema': 1, 'source': args.source, 'projects': args.projects, 'feed': args.feed,
                         'go': go_binary(args.go)})


def load_config(kit, private_json):
    cfg = private_json(Path(kit) / '.ai-factory-state' / CONFIG)
    return None if cfg is None else check_config(cfg)


def go_env():
    # The host's own Go setup (toolchain selection, caches) is kept; nothing is fetched.
    return {**os.environ, 'GOPROXY': 'off', 'LC_ALL': 'C'}


def run_dashboard(cfg, args, stdin=None):
    try:
        r = subprocess.run([cfg['go'], 'run', '-tags', 'nobundle', '.', '-projects', cfg['projects'], '-feed', cfg['feed'], *args],
                           cwd=cfg['source'], input=stdin, capture_output=True, timeout=TIMEOUT, env=go_env())
    except subprocess.TimeoutExpired:
        raise Blocked('the dashboard publisher did not finish in time') from None
    return r.returncode, r.stdout.decode('utf-8', 'replace'), r.stderr.decode('utf-8', 'replace')


def projects(cfg):
    """Dashboard project ids and roots from its projects config (the publisher validates it again)."""
    try:
        doc = json.loads(Path(cfg['projects']).read_bytes())
    except (OSError, ValueError):
        raise Blocked('the dashboard projects config is not readable JSON') from None
    rows = {}
    for e in doc if isinstance(doc, list) else []:
        if isinstance(e, dict) and isinstance(e.get('id'), str) and isinstance(e.get('root'), str):
            rows[e['id']] = e['root']
    if not rows: raise Blocked('the dashboard projects config lists no project')
    return rows


def validate_projects(cfg):
    """The dashboard's own strict validator, used once when the configuration is written."""
    code, _, _ = run_dashboard(cfg, ['-list-projects'])
    if code != 0: raise Blocked('the dashboard rejected its projects config')
    return projects(cfg)


def dashboard_id(cfg, root):
    """The dashboard id configured for this project root, or None."""
    for ident, path in projects(cfg).items():
        if path == str(root): return ident
    return None


def last_line(text):
    lines = [l.strip() for l in text.splitlines() if l.strip()]
    if not lines: return ''
    line = lines[-1]
    # Go's log prefix is a date and time; the publisher's messages carry no record text.
    parts = line.split(' ', 2)
    if len(parts) == 3 and parts[0].count('/') == 2 and parts[1].count(':') == 2: line = parts[2]
    return line[:300]


def head(root, git):
    value = git(root, 'HEAD')
    if not value or len(value) != 40: raise Blocked('could not read the project HEAD')
    return value


def status_record(raw, ident, revision, now):
    if len(raw) > MAX_INPUT: raise Blocked('status input is larger than 16 KiB')
    try:
        doc = json.loads(raw)
    except (ValueError, UnicodeDecodeError):
        raise Blocked('status input is not JSON') from None
    if not isinstance(doc, dict): raise Blocked('status input must be a JSON object')
    filled = sorted(set(doc) & FILLED)
    if filled: raise Blocked('status input must not set ' + ', '.join(filled) + ' (the command fills them)')
    unknown = sorted(set(doc) - AGENT_FIELDS)
    if unknown: raise Blocked('unknown status fields: ' + ', '.join(unknown))
    return {'schema': SCHEMA, 'project': ident, 'revision': revision,
            'updatedAt': now.strftime('%Y-%m-%dT%H:%M:%SZ'), **doc}


QUEUE_SCHEMA = 'factory-dashboard/queue/1'
QUEUE_INPUT = 256 * 1024    # larger than the record cap, so trimming can engage
QUEUE_MAX_BYTES, QUEUE_MAX_ITEMS = 32 * 1024, 64


def queue_record(raw, ident, now):
    """The queue record for the dashboard: the agent's items in its order, trimmed from the end to the record caps.

    `omitted` counts only what was trimmed here; listing every not-closed task is the agent's duty."""
    if len(raw) > QUEUE_INPUT: raise Blocked('queue input is larger than 256 KiB')
    try:
        doc = json.loads(raw)
    except (ValueError, UnicodeDecodeError):
        raise Blocked('queue input is not JSON') from None
    if not isinstance(doc, dict): raise Blocked('queue input must be a JSON object')
    filled = sorted(set(doc) & {'schema', 'project', 'updatedAt', 'omitted'})
    if filled: raise Blocked('queue input must not set ' + ', '.join(filled) + ' (the command fills them)')
    if set(doc) != {'items'} or not isinstance(doc['items'], list):
        raise Blocked('queue input must be {"items": [...]}')
    items = list(doc['items'])
    record = {'schema': QUEUE_SCHEMA, 'project': ident, 'updatedAt': now.strftime('%Y-%m-%dT%H:%M:%SZ'),
              'items': items[:QUEUE_MAX_ITEMS], 'omitted': max(0, len(items) - QUEUE_MAX_ITEMS)}
    while len(encode_record(record)) > QUEUE_MAX_BYTES and record['items']:
        record['items'].pop(); record['omitted'] += 1
    return record


def encode_record(record):
    return json.dumps(record, ensure_ascii=False).encode('utf-8')


def publish(cfg, record, apply, flag='-publish'):
    code, out, err = run_dashboard(cfg, [flag] + (['-apply'] if apply else []),
                                   stdin=json.dumps(record, ensure_ascii=False).encode('utf-8'))
    message = last_line(out) if code == 0 else last_line(err) or last_line(out) or f'exit {code}'
    return code == 0, message


def utcnow():
    return datetime.datetime.now(datetime.timezone.utc)
