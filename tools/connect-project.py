#!/usr/bin/env python3
"""Reproducible AI Factory *project connection* step.

This is NOT a package installer and does not re-implement `kit.py`. `kit.py` installs the
package into a managed root (`install`/`update`/`rollback`) and writes the package-install
receipt. This step connects a *project* (a checkout or an explicitly named worktree) to that
already-installed managed kit so a fresh agent session self-discovers the kit rules, the
project adapter and the existing read-only search contract — without anyone hand-feeding paths.

What it does, idempotently:
  * Writes a single delimited *managed block* into `AGENTS.local.md` that points at the
    canonical kit (`--managed-root`), imports the kit entry rules (`@<root>/rules/agent-entry.md`),
    and references the project adapter and the capture-search contract (by path, never copied).
  * Optionally points to an existing --task-index, retained unless explicitly changed/cleared; never creates a tracker.
  * Ensures `CLAUDE.local.md` imports `@AGENTS.local.md`.
  * Appends the local entrypoint paths to `.gitignore` (deduplicated), preserving existing rules.
  * Verifies the project pin/adapter/manifest identity against the installed kit (hashes from the
    real files) and reports mismatches. With the explicit opt-in `--reconcile-identity` it also
    rewrites ONLY the managed identity fields (version + release-manifest sha256) of known
    pin/package schemas to the installed kit, preserving history (`previous_pin`), caches and notes.
    The source `commit` is never guessed: since the installed kit records no verified commit, a stale
    `commit` is demoted to an explicit UNVERIFIED marker with the old SHA kept in `commit_superseded`,
    rather than left beside the refreshed hashes as if current. Unknown formats/schemas are reported
    before any write, never guessed. It never mints grants,
    never enables capture, never touches hooks/permissions/MCP/credentials/consent.

Applying requires a coordinated exclusive writer window over this project and managed kit.
Individual writes are guarded; the complete group is not an atomic transaction. On failure,
inspect any already-published files before retrying.

Only the delimited managed block is ever rewritten; everything outside it is preserved
byte-for-byte. A re-run with unchanged inputs writes nothing. A pre-existing *unmanaged* Factory
import is reported as a CONFLICT, never deleted silently and never duplicated.

One command (see --help). Default is a dry-run plan; pass --apply to write.
"""
import argparse
import hashlib
import json
import subprocess
import sys
import os, re, stat
import kit as installer
from pathlib import Path

BEGIN = "<!-- >>> ai-factory connect (managed block — regenerated by tools/connect-project.py; edit only OUTSIDE these markers) >>> -->"
END = "<!-- <<< ai-factory connect <<< -->"
IMPORT_RE = "rules/agent-entry.md"  # substring that identifies a kit entry-rules import


def read_text(p):
    raw = installer.regular(p)
    if raw is None:
        raise ValueError("missing file")
    return raw.decode("utf-8")


def sha256_file(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def kit_identity(managed_root):
    """Read the installed kit's identity from its own state — the package-install receipt."""
    root = installer.absolute(managed_root)
    state = installer.absolute(root / installer.STATE)
    st = state.stat()
    if st.st_uid != os.getuid() or stat.S_IMODE(st.st_mode) & 0o077:
        raise ValueError("installed state must be private and owned")
    if installer.pending(root):
        raise ValueError("unfinished install transaction")
    installed = installer.current(root)
    txid = installed.get("latest")
    if not isinstance(txid, str) or not re.fullmatch(r"[a-f0-9]{32}", txid):
        raise ValueError("invalid installed transaction")
    receipt = installer.read_tx(state / "receipts" / (txid + ".json"))
    plan = receipt.get("plan", {})
    if (receipt.get("status") != "APPLIED" or receipt.get("id") != txid
            or plan.get("root") != str(root)
            or any(installed.get(k) != plan.get(k) for k in ("files", "version", "components"))):
        raise ValueError("installed receipt mismatch")
    for name, expected in installed["files"].items():
        if installer.signature(root / installer.relative(name)) != expected:
            raise ValueError("installed file mismatch")
    for required in ["release-manifest.json", "checksums.sha256", "rules/agent-entry.md"]:
        if required not in installed["files"]:
            raise ValueError("required installed file absent")
    manifest_data = installer.read_json(root / "release-manifest.json")
    if (manifest_data.get("version") != installed["version"]
            or installer.digest(installer.encode(manifest_data)) != plan.get("release_sha256")):
        raise ValueError("release identity mismatch")
    version = installed.get("version")
    components = installed.get("components", [])
    txid = installed.get("latest")  # the package-install transaction (NOT a project transaction)
    receipt = root / ".ai-factory-state" / "receipts" / f"{txid}.json" if txid else None
    manifest = root / "release-manifest.json"
    manifest_sha = sha256_file(manifest) if manifest.exists() else None
    entry_rules = root / "rules" / "agent-entry.md"
    return {
        "managed_root": str(root),
        "version": version,
        "components": components,
        "install_transaction": txid,
        "install_receipt": str(receipt) if receipt else None,
        "release_manifest_sha256": manifest_sha,
        "entry_rules": str(entry_rules),
        "entry_rules_exists": entry_rules.exists(),
    }


GLOBAL_ROUTES = (
    "ai-factory/ai-factory-plan.md", "ai-factory/workflow.md",
    "ai-factory/pre-code-checkpoint.md", "ai-factory/review-handoff.md",
)
ADAPTER_ROUTES = (".ai/project/adapter.md", ".ai/agents/ai-factory.md",
                  "work/rules/ai-factory.md", "docs/development/ai-factory.md")
SEARCH_ROUTES = (".ai/project/capture-search.md", ".ai/agents/capture-search.md")


def route_reference(project, value):
    """Validate a pointer without copying its contents into output or generated files.

    Explicit absolute references remain supported. Symlinks (including ancestors),
    traversal, markup and special files are deliberately not accepted.
    """
    if not isinstance(value, str) or not re.fullmatch(r"[A-Za-z0-9_./ -]+", value):
        raise ValueError("route must be a plain Markdown file path")
    ref = Path(value)
    if ref.suffix != '.md' or str(ref) != value:
        raise ValueError("route must be a canonical Markdown file path")
    path = installer.absolute(ref if ref.is_absolute() else project / installer.relative(value))
    before = installer.signature(path)
    if before is None:
        raise ValueError("route file is missing")
    if not before['mode'] & 0o444 or not os.access(path, os.R_OK):
        raise ValueError("route file is not readable")
    raw = installer.regular(path)
    if raw is None:
        raise ValueError("route disappeared while planning")
    raw.decode('utf-8')
    if installer.digest(raw) != before['sha256'] or installer.signature(path) != before:
        raise ValueError("route changed while planning")
    return path, before


def select_route(project, explicit, candidates, label, baseline):
    value = explicit
    if value is None:
        for candidate in candidates:
            # lexists also finds dangling symlinks: never silently downgrade a broken route.
            if os.path.lexists(project / candidate):
                value = candidate
                break
    if value is not None:
        try:
            path, signature = route_reference(project, value)
        except (ValueError, OSError, UnicodeError) as exc:
            raise ValueError(f"{label}: invalid, missing or unreadable route ({type(exc).__name__})") from exc
        if path in baseline and baseline[path] != signature:
            raise ValueError(f"{label}: route changed since destination snapshot")
        baseline[path] = signature
    return value


def build_block(kit, adapter_rel, search_rel, project_root, task_index=None, global_only=False, dashboard=None):
    """The managed block body (no markers). Deterministic given inputs."""
    lines = [
        "## AI Factory connection (managed)",
        "",
        f"Canonical kit (single copy, not vendored here): `{kit['managed_root']}` — always the latest "
        "version installed there; this block is bound to no version, hash or commit.",
        f"Current kit identity: read `{kit['managed_root']}/.ai-factory-state/installed.json` (`latest`) "
        "and its receipt at the time of use.",
        "",
        "Kit entry rules (§subagent-stream-to-file / §silent-agent / §session-continuation) are "
        "imported from the canonical kit below; skill bodies are never copied into this project.",
        "",
        f"Before work, skills or delegation, explicitly read `{kit['entry_rules']}`. "
        "The @ import below is supported Claude syntax, not a claim that other hosts load it automatically.",
        "",
        f"@{kit['entry_rules']}",
        "",
    ]
    if task_index:
        lines.extend([
            '<!-- ai-factory-task-index: ' + json.dumps(task_index) + ' -->',
            f"Task index (existing navigation, not authorization): `{task_index}`. "
            "Read its explicit primary task/phase pointer before continuation; never select by recency. "
            "Keep readiness, handoff and evidence in that primary record; do not create a second tracker.",
            "",
        ])
    if global_only:
        lines.extend([
            "<!-- ai-factory-route: global-only -->",
            "Factory workflow: global-only; existing project architecture, rules and task records remain authoritative.",
            *[f"Shared Factory reference: `{Path(kit['managed_root']) / name}`." for name in GLOBAL_ROUTES],
        ])
    elif adapter_rel:
        lines.append(f"Project adapter (local routing, authoritative over kit defaults): `{adapter_rel}`.")
    else:
        lines.append("Project adapter: none found in this checkout (worktree/main may differ).")
    if search_rel:
        lines.append(
            f"Conversation-archive **read-only search** contract: `{search_rel}` — it holds the "
            "GET route, the agent search-grant headers and the LOCAL credential file paths "
            "(secret values are never stored or printed). GET only; no POST, no hook run, do not "
            "use the operator secret for search."
        )
    else:
        lines.append(
            "Conversation-archive search: not configured for this project (no capture-search "
            "contract found). Do not invent credentials or substitute the operator secret."
        )
    if dashboard:
        root = kit['managed_root']
        lines.append(
            f"Dashboard status for this project: id `{dashboard}`. After a stage of the primary task is "
            f"recorded (and after your own commit), publish it as in `{root}/docs/dashboard-status.md`: "
            f"`python3 -I {root}/tools/kit.py project status --root {root} --project {dashboard} [--apply] < status.json`. "
            "Evidence only from the task record; no paths, URLs or secrets."
        )
    return "\n".join(lines).rstrip() + "\n"


DASHBOARD_LINE = re.compile(r'Dashboard status for this project: id `([a-z0-9][a-z0-9-]{0,62})`')
DASHBOARD_ID = re.compile(r'[a-z0-9][a-z0-9-]{0,62}')


def prior_dashboard(existing):
    """The dashboard id this tool recorded in its managed block, retained on reconnect."""
    if not existing or BEGIN not in existing:
        return None
    found = DASHBOARD_LINE.findall(existing.split(BEGIN, 1)[1].split(END, 1)[0])
    if len(found) > 1:
        raise ValueError('ambiguous managed dashboard pointer')
    return found[0] if found else None


SEARCH_LINE = re.compile(r'Conversation-archive \*\*read-only search\*\* contract: `([^`\n]+)`')


def prior_search_contract(existing):
    """The search route this tool recorded in its managed block, retained on reconnect."""
    if not existing or BEGIN not in existing:
        return None
    body = existing.split(BEGIN, 1)[1].split(END, 1)[0]
    found = SEARCH_LINE.findall(body)
    if len(found) > 1:
        raise ValueError('ambiguous managed search contract')
    return found[0] if found else None


def task_index_pointer(project, existing, requested=None, clear=False):
    """Retain only a deliberately recorded pointer inside our managed block; never infer a path."""
    validate_markers(existing)
    prior = None
    if existing and BEGIN in existing:
        body = existing.split(BEGIN, 1)[1].split(END, 1)[0]
        lines = [line for line in body.splitlines() if 'ai-factory-task-index:' in line]
        if len(lines) > 1:
            raise ValueError('ambiguous managed task index')
        if lines:
            match = re.fullmatch(r'<!-- ai-factory-task-index: (.+) -->', lines[0])
            if not match:
                raise ValueError('invalid managed task index marker')
            prior = json.loads(match.group(1))
            if not isinstance(prior, str):
                raise ValueError('invalid managed task index')
    value = None if clear else (requested if requested is not None else prior)
    if value is None:
        return None, None
    if not re.fullmatch(r'[A-Za-z0-9_./ -]+', value) or Path(value).suffix != '.md':
        raise ValueError('task index must be a plain project-relative Markdown path')
    rel = installer.relative(value)
    if value in ('AGENTS.local.md', 'CLAUDE.local.md'):
        raise ValueError('task index must not be a generated entrypoint')
    path = installer.absolute(project / rel)
    raw = installer.regular(path)
    if raw is None or len(raw) > 524288:
        raise ValueError('missing or oversized task index; no tracker is created')
    raw.decode('utf-8')
    return value, (path, installer.signature(path))


def validate_markers(text):
    if text is None:
        return
    begins, ends = text.count(BEGIN), text.count(END)
    if (begins, ends) == (0, 0):
        return
    if (begins, ends) != (1, 1) or text.index(BEGIN) >= text.index(END):
        raise ValueError("ambiguous managed block markers")


def splice_managed_block(existing_text, block_body):
    """Return (new_text, action). Replace between markers if present, else append. Preserve the rest.

    `wrapped` carries NO trailing newline; create/append add exactly one, and a replace relies on
    the newline already captured in `post`, so a re-run with unchanged inputs is byte-idempotent.
    """
    validate_markers(existing_text)
    wrapped = f"{BEGIN}\n{block_body}{END}"
    if existing_text is None:
        return wrapped + "\n", "create"
    if BEGIN in existing_text and END in existing_text:
        pre = existing_text.split(BEGIN, 1)[0]
        post = existing_text.split(END, 1)[1]
        new = pre + wrapped + post
        return new, ("noop" if new == existing_text else "update-block")
    # append, preserving every existing byte; ensure a separating newline
    sep = "" if existing_text.endswith("\n\n") else ("\n" if existing_text.endswith("\n") else "\n\n")
    new = existing_text + sep + wrapped + "\n"
    return new, "append"


def detect_unmanaged_import(existing_text):
    """A kit entry-rules import OUTSIDE the managed block is an unmanaged connection → CONFLICT."""
    if existing_text is None:
        return []
    outside = existing_text
    if BEGIN in existing_text and END in existing_text:
        outside = existing_text.split(BEGIN, 1)[0] + existing_text.split(END, 1)[1]
    hits = []
    for ln in outside.splitlines():
        s = ln.strip()
        if s.startswith("@") and IMPORT_RE in s:
            hits.append(s)
    return hits


def ensure_claude_import(existing_text):
    """CLAUDE.local.md must import @AGENTS.local.md. Managed block, idempotent."""
    validate_markers(existing_text)
    want = "@AGENTS.local.md"
    if existing_text and any(line.strip() == want for line in existing_text.splitlines()):
        return existing_text, "present"  # already connected, do not duplicate
    body = (
        "## AI Factory connection (managed)\n\n"
        "Local project wiring imports the local agents entrypoint:\n\n"
        f"{want}\n"
    )
    return splice_managed_block(existing_text, body)


def gitignore_plan(gitignore_path, wanted):
    """Lines to add (preserve order, dedupe). Idempotent."""
    existing = []
    if gitignore_path.exists():
        existing = read_text(gitignore_path).splitlines()
    have = set(x.strip() for x in existing)
    to_add = [w for w in wanted if w not in have]
    return existing, to_add


def git_tracked(git_root, relpath):
    try:
        r = subprocess.run(["git", "-C", str(git_root), "ls-files", "--error-unmatch", relpath],
                           capture_output=True, text=True)
        return r.returncode == 0
    except Exception:
        return False


PIN_LOCATIONS = (
    ".ai/project/ai-factory-pin.json",
    ".ai/agents/ai-factory-package.json",
    "work/rules/ai-factory-package.json",
    "docs/development/ai-factory-package.json",
)


def identity_shape(obj):
    """Known pin/package identity shapes → (block_key, version_key, manifest_sha_key). Else None.

    Only these two reviewed schemas are reconciled; any other shape is reported, never guessed.
    """
    if obj.get("schema") == "ai-factory-pin/1" and isinstance(obj.get("source"), dict):
        return ("source", "version", "release_manifest_file_sha256")
    if obj.get("schema_version") == 1 and isinstance(obj.get("package"), dict):
        return ("package", "version", "release_manifest_sha256")
    return None


def verify_consistency(project_root, kit):
    """Report whether project pin/adapter/manifest record the installed kit identity. Read-only.

    This is the no-update MISMATCH report; the actual rewrite is `reconcile_identity` (opt-in).
    """
    findings = []
    for rel in PIN_LOCATIONS:
        p = project_root / rel
        if not p.exists():
            continue
        try:
            d = json.loads(read_text(p))
        except Exception:
            findings.append(f"pin {rel}: UNREADABLE")
            continue
        shape = identity_shape(d)
        if not shape:
            findings.append(f"pin {rel}: UNKNOWN schema (not reconcilable without review)")
            continue
        bk, vk, mk = shape
        blk = d.get(bk, {})
        ok = (blk.get(vk) == kit["version"] and blk.get(mk) == kit["release_manifest_sha256"])
        findings.append(f"pin {rel}: version/manifest {'MATCH' if ok else 'MISMATCH'} installed kit")
    if not findings:
        findings.append("pin: none found in this checkout")
    return findings


def reconcile_identity(project_root, kit, apply, writes=None):
    """Rewrite ONLY the managed identity fields (version + release-manifest sha256) of known
    pin/package files to the installed kit, from the real installed state.

    Preserves every other byte: user text, `previous_pin`/history, `cache.required_files`, notes,
    install receipts, and `commit` (the source git commit is NOT derivable from the installed kit,
    so it is never guessed — only reported). A file whose formatting is not canonical, whose schema
    is unknown, or whose identity block/keys are absent is REPORTED and left untouched (shown before
    any write, never guessed). The edit is surgical and idempotent: a re-run after a successful
    reconcile writes nothing. Returns (results, wrote_any).
    """
    results = []
    wrote = False
    want_version = kit["version"]
    want_manifest = kit["release_manifest_sha256"]
    for rel in PIN_LOCATIONS:
        p = project_root / rel
        if not p.exists():
            continue
        raw = read_text(p)
        try:
            obj = json.loads(raw)
        except Exception:
            results.append({"file": rel, "status": "conflict",
                            "detail": "UNREADABLE JSON — shown, not written"})
            continue
        canon = json.dumps(obj, indent=2, ensure_ascii=False) + ("\n" if raw.endswith("\n") else "")
        if canon != raw:
            results.append({"file": rel, "status": "conflict",
                            "detail": "non-canonical formatting — reconcile skipped to avoid "
                                      "reformatting the file (shown, not written)"})
            continue
        shape = identity_shape(obj)
        if not shape:
            results.append({"file": rel, "status": "conflict",
                            "detail": "UNKNOWN pin/package schema — shown, not written; reconcile manually"})
            continue
        bk, vk, mk = shape
        block = obj[bk]
        if vk not in block or mk not in block:
            results.append({"file": rel, "status": "conflict",
                            "detail": f"identity keys `{vk}`/`{mk}` absent in `{bk}` — shown, not written"})
            continue
        changes = []
        if block.get(vk) != want_version:
            changes.append({"key": f"{bk}.{vk}", "old": block.get(vk), "new": want_version})
        if want_manifest is not None and block.get(mk) != want_manifest:
            changes.append({"key": f"{bk}.{mk}", "old": block.get(mk), "new": want_manifest})
        # The installed kit records no verified git commit (install is keyed on version + manifest
        # digest, not a SHA). So a stale `commit` must NOT sit next to the refreshed hashes as if it
        # were current: demote it to an explicit unverified marker and keep the old SHA in history.
        # We never guess a SHA. Idempotent: once commit is null, there is nothing left to demote.
        commit_demote = ("commit" in block and block.get("commit") is not None)
        if commit_demote:
            changes.append({"key": f"{bk}.commit", "old": block.get("commit"), "new": None,
                            "reason": "UNVERIFIED_FOR_CURRENT_PACKAGE (installed kit has no commit link); "
                                      "old value preserved in commit_superseded"})
        entry = {"file": rel, "changes": changes}
        if not changes:
            entry["status"] = "match"
            results.append(entry)
            continue
        if apply:
            block[vk] = want_version
            if want_manifest is not None:
                block[mk] = want_manifest
            if commit_demote:
                block["commit_superseded"] = block["commit"]
                block["commit"] = None
                block["commit_status"] = ("UNVERIFIED_FOR_CURRENT_PACKAGE: the installed kit records no "
                                          "git commit; reconcile against a verified release commit before "
                                          "relying on it. Previous value preserved in commit_superseded.")
            if writes is None:
                raise ValueError("guarded write plan required")
            writes[p] = (json.dumps(obj, indent=2, ensure_ascii=False) + ("\n" if raw.endswith("\n") else "")).encode("utf-8")
            wrote = True
            entry["status"] = "updated"
        else:
            entry["status"] = "would-update"
        results.append(entry)
    if not results:
        results.append({"file": None, "status": "none",
                        "detail": "no pin/package file found in this checkout"})
    return results, wrote


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--managed-root", required=True, help="installed kit root (where kit.py installed the package)")
    ap.add_argument("--project", required=True, help="project root: a checkout OR an explicit worktree path")
    routing = ap.add_mutually_exclusive_group()
    routing.add_argument("--adapter", help="existing readable project-relative or explicit absolute Markdown adapter")
    routing.add_argument("--global-only", action="store_true", help="use installed shared workflow without a local Factory adapter")
    search = ap.add_mutually_exclusive_group()
    search.add_argument("--search-contract", help="path to the read-only search contract (e.g. .ai/project/capture-search.md); retained on future reconnects")
    search.add_argument("--clear-search-contract", action="store_true", help="remove only the managed search-contract pointer; leave its file untouched")
    dash = ap.add_mutually_exclusive_group()
    dash.add_argument("--dashboard-project", help="dashboard project id: adds the status-publishing pointer; retained on future reconnects")
    dash.add_argument("--clear-dashboard-project", action="store_true", help="remove only the managed dashboard pointer")
    group = ap.add_mutually_exclusive_group()
    group.add_argument("--task-index", help="existing project-relative Markdown task index; retained on future reconnects")
    group.add_argument("--clear-task-index", action="store_true", help="remove only the managed task-index pointer; leave its file untouched")
    ap.add_argument("--gitignore-extra", action="append", default=[], help="extra local path to gitignore (repeatable)")
    ap.add_argument("--git-root", help="git root to check tracked-status against (default: --project)")
    ap.add_argument("--reconcile-identity", action="store_true",
                    help="also reconcile stale pin/adapter/manifest identity (version + release-manifest "
                         "sha) to the installed kit; preserves history and unknown shapes. Without this "
                         "flag the pin is only reported (MISMATCH), never rewritten.")
    ap.add_argument("--apply", action="store_true", help="write changes (default: dry-run plan)")
    a = ap.parse_args(argv)

    project = installer.absolute(a.project)
    git_root = Path(a.git_root) if a.git_root else project
    report = {"actions": [], "conflicts": [], "consistency": [], "untouched": [
        "hooks", "permissions", "MCP", "credentials", "consent", "grants", "capture (not enabled)"]}

    # Validate every possible destination before reads or any write.
    targets = [project / n for n in ["AGENTS.local.md", "CLAUDE.local.md", ".gitignore", *PIN_LOCATIONS]]
    baseline = {p: installer.signature(p) for p in targets}
    kit = kit_identity(a.managed_root)
    if not kit["entry_rules_exists"]:
        print(json.dumps({"status": "BLOCKED", "reason": "managed root has no rules/agent-entry.md"}, indent=2))
        return 1
    report["kit"] = kit

    # An explicit global-only choice survives ordinary reconnect/update. An explicit
    # adapter is the only way to opt back into local routing; never infer from .ai.
    try:
        existing_agents = read_text(project / 'AGENTS.local.md') if (project / 'AGENTS.local.md').exists() else None
        validate_markers(existing_agents)
        global_only = a.global_only
        if existing_agents and BEGIN in existing_agents and a.adapter is None:
            managed = existing_agents.split(BEGIN, 1)[1].split(END, 1)[0]
            route_markers = [line for line in managed.splitlines() if 'ai-factory-route:' in line]
            if route_markers:
                if route_markers != ['<!-- ai-factory-route: global-only -->']:
                    raise ValueError('ambiguous managed routing marker')
                global_only = True
        # A recorded search route survives reconnect/update like the task index; a
        # missing recorded route blocks instead of being silently dropped or replaced.
        search_explicit = a.search_contract
        if search_explicit is None and not a.clear_search_contract:
            search_explicit = prior_search_contract(existing_agents)
        dashboard = a.dashboard_project
        if dashboard is not None and not DASHBOARD_ID.fullmatch(dashboard):
            raise ValueError('invalid dashboard project id')
        if dashboard is None and not a.clear_dashboard_project:
            dashboard = prior_dashboard(existing_agents)

    except (ValueError, OSError, UnicodeError) as exc:
        report['status'] = 'BLOCKED'
        report['conflicts'].append(str(exc))
        print(json.dumps(report, indent=2, ensure_ascii=False))
        return 1

    # Validate all referenced files before planning any publication. Their snapshots
    # join destination guards so removal/drift cannot yield a false-green apply.
    try:
        adapter_rel = select_route(project, a.adapter, () if global_only else ADAPTER_ROUTES,
                                   "adapter", baseline)
        search_rel = select_route(project, search_explicit,
                                  () if a.clear_search_contract else SEARCH_ROUTES,
                                  "search-contract", baseline)
        if global_only:
            installed = installer.current(Path(kit['managed_root']))
            for name in GLOBAL_ROUTES:
                if name not in installed['files']:
                    raise ValueError("global workflow reference is not installed")
                select_route(Path(kit['managed_root']), name, (), "global workflow", baseline)
    except (ValueError, OSError, UnicodeError) as exc:
        report['status'] = 'BLOCKED'
        report['conflicts'].append(str(exc))
        print(json.dumps(report, indent=2, ensure_ascii=False))
        return 1
    report['routes'] = {'mode': 'global-only' if global_only else 'local',
                        'adapter': adapter_rel, 'search_contract': search_rel,
                        'validation': 'readable-files-only; contents, endpoint and authorization not verified'}

    # --- AGENTS.local.md ---
    agents_p = project / "AGENTS.local.md"
    agents_text = read_text(agents_p) if agents_p.exists() else None
    try:
        validate_markers(agents_text)
        claude_check = project / "CLAUDE.local.md"
        validate_markers(read_text(claude_check) if claude_check.exists() else None)
    except ValueError as exc:
        report["status"] = "BLOCKED"
        report["conflicts"].append(str(exc))
        print(json.dumps(report, indent=2, ensure_ascii=False))
        return 1
    task_index, pointer_baseline = task_index_pointer(project, agents_text, a.task_index, a.clear_task_index)
    if pointer_baseline:
        baseline[pointer_baseline[0]] = pointer_baseline[1]
    report["task_index"] = task_index
    block_body = build_block(kit, adapter_rel, search_rel, project, task_index, global_only, dashboard)
    conflicts = detect_unmanaged_import(agents_text)
    for c in conflicts:
        report["conflicts"].append(f"AGENTS.local.md has an UNMANAGED kit import outside the managed block: `{c}` "
                                   "— left in place (not deleted, not duplicated); reconcile it manually.")
    agents_new, agents_action = splice_managed_block(agents_text, block_body)
    report["actions"].append({"file": "AGENTS.local.md", "action": agents_action})

    # --- CLAUDE.local.md ---
    claude_p = project / "CLAUDE.local.md"
    claude_text = read_text(claude_p) if claude_p.exists() else None
    claude_new, claude_action = ensure_claude_import(claude_text)
    report["actions"].append({"file": "CLAUDE.local.md", "action": claude_action})

    # --- .gitignore ---
    gi_p = project / ".gitignore"
    wanted = ["AGENTS.local.md", "CLAUDE.local.md"] + list(a.gitignore_extra)
    gi_existing, gi_add = gitignore_plan(gi_p, wanted)
    report["actions"].append({"file": ".gitignore", "action": ("add:" + ",".join(gi_add)) if gi_add else "noop"})
    for w in wanted:
        if git_tracked(git_root, w):
            report["conflicts"].append(f".gitignore target `{w}` is TRACKED in git — shown, not removed; "
                                       "no automatic `git rm` is run.")

    report["consistency"] = verify_consistency(project, kit)

    # Opt-in: actually reconcile stale identity fields. Conflicts/unknowns are surfaced BEFORE any
    # write so they are shown, never guessed. Writing only happens with --apply AND this flag.
    if a.reconcile_identity:
        recon, _ = reconcile_identity(project, kit, apply=False)
        report["identity_reconcile"] = recon
        for r in recon:
            if r.get("status") == "conflict":
                report["conflicts"].append(
                    f"pin {r['file']}: {r['detail']}")

    if report["conflicts"]:
        report["status"] = "BLOCKED"
        print(json.dumps(report, indent=2, ensure_ascii=False))
        return 1

    if a.apply:
        writes = {}
        if a.reconcile_identity:
            report["identity_reconcile"], _ = reconcile_identity(project, kit, apply=True, writes=writes)
        if agents_action != "noop":
            writes[agents_p] = agents_new.encode("utf-8")
        if claude_action not in ("present", "noop"):
            writes[claude_p] = claude_new.encode("utf-8")
        if gi_add:
            raw = installer.regular(gi_p) or b""
            newline = b"\r\n" if b"\r\n" in raw else b"\n"
            text = raw + (newline if raw and not raw.endswith(b"\n") else b"")
            if b"# AI Factory local connection" not in raw:
                text += newline + b"# AI Factory local connection (machine-specific; never committed)" + newline
            writes[gi_p] = text + newline.join(w.encode("utf-8") for w in gi_add) + newline
        # Explicit coordinated writer window: reject any drift before first publication.
        if kit_identity(a.managed_root) != kit:
            raise ValueError("installed kit changed while planning")
        for path, expected in baseline.items():
            if installer.signature(path) != expected:
                raise ValueError("project changed while planning")
        for path, data in writes.items():
            expected = baseline[path]
            desired = {"sha256": installer.digest(data), "mode": expected["mode"] if expected else 0o600}
            installer.guarded_write(path, expected, desired, data)
        report["status"] = "APPLIED"
    else:
        report["status"] = "PLANNED (dry-run; pass --apply to write)"

    print(json.dumps(report, indent=2, ensure_ascii=False))
    return 0


