#!/usr/bin/env python3
"""Reproducible AI Factory *project connection* step.

This is NOT a package installer and does not re-implement `kit.py`. `kit.py` installs the
package into a managed root (`install`/`update`/`rollback`) and writes the package-install
receipt. This step connects a *project* (a checkout or an explicitly named worktree) to that
already-installed managed kit so a fresh agent session self-discovers the kit rules, the
project adapter and the existing read-only search contract — without anyone hand-feeding paths.

What it does, idempotently:
  * Writes a single delimited *managed block* into `AGENTS.local.md` that points at the
    canonical kit (`--managed-root`), imports the kit entry rules (`@<root>/rules/agent-entry.md`),
    and references the project adapter and the capture-search contract (by path, never copied).
  * Ensures `CLAUDE.local.md` imports `@AGENTS.local.md`.
  * Appends the local entrypoint paths to `.gitignore` (deduplicated), preserving existing rules.
  * Verifies the project pin/adapter/manifest identity against the installed kit (hashes from the
    real files) and reports mismatches. With the explicit opt-in `--reconcile-identity` it also
    rewrites ONLY the managed identity fields (version + release-manifest sha256) of known
    pin/package schemas to the installed kit, preserving history (`previous_pin`), caches and notes.
    The source `commit` is never guessed: since the installed kit records no verified commit, a stale
    `commit` is demoted to an explicit UNVERIFIED marker with the old SHA kept in `commit_superseded`,
    rather than left beside the refreshed hashes as if current. Unknown formats/schemas are reported
    before any write, never guessed. It never mints grants,
    never enables capture, never touches hooks/permissions/MCP/credentials/consent.

Only the delimited managed block is ever rewritten; everything outside it is preserved
byte-for-byte. A re-run with unchanged inputs writes nothing. A pre-existing *unmanaged* Factory
import is reported as a CONFLICT, never deleted silently and never duplicated.

One command (see --help). Default is a dry-run plan; pass --apply to write.
"""
import argparse
import hashlib
import json
import subprocess
import sys
from pathlib import Path

BEGIN = "<!-- >>> ai-factory connect (managed block — regenerated by tools/connect-project.py; edit only OUTSIDE these markers) >>> -->"
END = "<!-- <<< ai-factory connect <<< -->"
IMPORT_RE = "rules/agent-entry.md"  # substring that identifies a kit entry-rules import


def sha256_file(p):
    return hashlib.sha256(Path(p).read_bytes()).hexdigest()


def kit_identity(managed_root):
    """Read the installed kit's identity from its own state — the package-install receipt."""
    root = Path(managed_root)
    installed = json.loads((root / ".ai-factory-state" / "installed.json").read_text())
    version = installed.get("version")
    components = installed.get("components", [])
    txid = installed.get("latest")  # the package-install transaction (NOT a project transaction)
    receipt = root / ".ai-factory-state" / "receipts" / f"{txid}.json" if txid else None
    manifest = root / "release-manifest.json"
    manifest_sha = sha256_file(manifest) if manifest.exists() else None
    entry_rules = root / "rules" / "agent-entry.md"
    return {
        "managed_root": str(root),
        "version": version,
        "components": components,
        "install_transaction": txid,
        "install_receipt": str(receipt) if receipt else None,
        "release_manifest_sha256": manifest_sha,
        "entry_rules": str(entry_rules),
        "entry_rules_exists": entry_rules.exists(),
    }


def build_block(kit, adapter_rel, search_rel, project_root):
    """The managed block body (no markers). Deterministic given inputs."""
    lines = [
        "## AI Factory connection (managed)",
        "",
        f"Canonical kit (single copy, not vendored here): `{kit['managed_root']}` — "
        f"version `{kit['version']}`"
        + (f", release-manifest sha256 `{kit['release_manifest_sha256']}`" if kit['release_manifest_sha256'] else "")
        + ".",
        f"Package-install receipt (the managed-root install, not a project transaction): "
        f"`{kit['install_receipt']}`." if kit['install_receipt'] else
        "Package-install receipt: (managed root reports no install transaction).",
        "",
        "Kit entry rules (§subagent-stream-to-file / §silent-agent / §session-continuation) are "
        "imported from the canonical kit below; skill bodies are never copied into this project.",
        "",
        f"@{kit['entry_rules']}",
        "",
    ]
    if adapter_rel:
        lines.append(f"Project adapter (local routing, authoritative over kit defaults): `{adapter_rel}`.")
    else:
        lines.append("Project adapter: none found in this checkout (worktree/main may differ).")
    if search_rel:
        lines.append(
            f"Conversation-archive **read-only search** contract: `{search_rel}` — it holds the "
            "GET route, the agent search-grant headers and the LOCAL credential file paths "
            "(secret values are never stored or printed). GET only; no POST, no hook run, do not "
            "use the operator secret for search."
        )
    else:
        lines.append(
            "Conversation-archive search: not configured for this project (no capture-search "
            "contract found). Do not invent credentials or substitute the operator secret."
        )
    return "\n".join(lines).rstrip() + "\n"


def splice_managed_block(existing_text, block_body):
    """Return (new_text, action). Replace between markers if present, else append. Preserve the rest.

    `wrapped` carries NO trailing newline; create/append add exactly one, and a replace relies on
    the newline already captured in `post`, so a re-run with unchanged inputs is byte-idempotent.
    """
    wrapped = f"{BEGIN}\n{block_body}{END}"
    if existing_text is None:
        return wrapped + "\n", "create"
    if BEGIN in existing_text and END in existing_text:
        pre = existing_text.split(BEGIN, 1)[0]
        post = existing_text.split(END, 1)[1]
        new = pre + wrapped + post
        return new, ("noop" if new == existing_text else "update-block")
    # append, preserving every existing byte; ensure a separating newline
    sep = "" if existing_text.endswith("\n\n") else ("\n" if existing_text.endswith("\n") else "\n\n")
    new = existing_text + sep + wrapped + "\n"
    return new, "append"


def detect_unmanaged_import(existing_text):
    """A kit entry-rules import OUTSIDE the managed block is an unmanaged connection → CONFLICT."""
    if existing_text is None:
        return []
    outside = existing_text
    if BEGIN in existing_text and END in existing_text:
        outside = existing_text.split(BEGIN, 1)[0] + existing_text.split(END, 1)[1]
    hits = []
    for ln in outside.splitlines():
        s = ln.strip()
        if s.startswith("@") and IMPORT_RE in s:
            hits.append(s)
    return hits


def ensure_claude_import(existing_text):
    """CLAUDE.local.md must import @AGENTS.local.md. Managed block, idempotent."""
    want = "@AGENTS.local.md"
    if existing_text and want in existing_text:
        return existing_text, "present"  # already connected, do not duplicate
    body = (
        "## AI Factory connection (managed)\n\n"
        "Local project wiring imports the local agents entrypoint:\n\n"
        f"{want}\n"
    )
    return splice_managed_block(existing_text, body)


def gitignore_plan(gitignore_path, wanted):
    """Lines to add (preserve order, dedupe). Idempotent."""
    existing = []
    if gitignore_path.exists():
        existing = gitignore_path.read_text().splitlines()
    have = set(x.strip() for x in existing)
    to_add = [w for w in wanted if w not in have]
    return existing, to_add


def git_tracked(git_root, relpath):
    try:
        r = subprocess.run(["git", "-C", str(git_root), "ls-files", "--error-unmatch", relpath],
                           capture_output=True, text=True)
        return r.returncode == 0
    except Exception:
        return False


PIN_LOCATIONS = (
    ".ai/project/ai-factory-pin.json",
    ".ai/agents/ai-factory-package.json",
    "work/rules/ai-factory-package.json",
    "docs/development/ai-factory-package.json",
)


def identity_shape(obj):
    """Known pin/package identity shapes → (block_key, version_key, manifest_sha_key). Else None.

    Only these two reviewed schemas are reconciled; any other shape is reported, never guessed.
    """
    if obj.get("schema") == "ai-factory-pin/1" and isinstance(obj.get("source"), dict):
        return ("source", "version", "release_manifest_file_sha256")
    if obj.get("schema_version") == 1 and isinstance(obj.get("package"), dict):
        return ("package", "version", "release_manifest_sha256")
    return None


def verify_consistency(project_root, kit):
    """Report whether project pin/adapter/manifest record the installed kit identity. Read-only.

    This is the no-update MISMATCH report; the actual rewrite is `reconcile_identity` (opt-in).
    """
    findings = []
    for rel in PIN_LOCATIONS:
        p = project_root / rel
        if not p.exists():
            continue
        try:
            d = json.loads(p.read_text())
        except Exception:
            findings.append(f"pin {rel}: UNREADABLE")
            continue
        shape = identity_shape(d)
        if not shape:
            findings.append(f"pin {rel}: UNKNOWN schema (not reconcilable without review)")
            continue
        bk, vk, mk = shape
        blk = d.get(bk, {})
        ok = (blk.get(vk) == kit["version"] and blk.get(mk) == kit["release_manifest_sha256"])
        findings.append(f"pin {rel}: version/manifest {'MATCH' if ok else 'MISMATCH'} installed kit")
    if not findings:
        findings.append("pin: none found in this checkout")
    return findings


def reconcile_identity(project_root, kit, apply):
    """Rewrite ONLY the managed identity fields (version + release-manifest sha256) of known
    pin/package files to the installed kit, from the real installed state.

    Preserves every other byte: user text, `previous_pin`/history, `cache.required_files`, notes,
    install receipts, and `commit` (the source git commit is NOT derivable from the installed kit,
    so it is never guessed — only reported). A file whose formatting is not canonical, whose schema
    is unknown, or whose identity block/keys are absent is REPORTED and left untouched (shown before
    any write, never guessed). The edit is surgical and idempotent: a re-run after a successful
    reconcile writes nothing. Returns (results, wrote_any).
    """
    results = []
    wrote = False
    want_version = kit["version"]
    want_manifest = kit["release_manifest_sha256"]
    for rel in PIN_LOCATIONS:
        p = project_root / rel
        if not p.exists():
            continue
        raw = p.read_text()
        try:
            obj = json.loads(raw)
        except Exception:
            results.append({"file": rel, "status": "conflict",
                            "detail": "UNREADABLE JSON — shown, not written"})
            continue
        canon = json.dumps(obj, indent=2, ensure_ascii=False) + ("\n" if raw.endswith("\n") else "")
        if canon != raw:
            results.append({"file": rel, "status": "conflict",
                            "detail": "non-canonical formatting — reconcile skipped to avoid "
                                      "reformatting the file (shown, not written)"})
            continue
        shape = identity_shape(obj)
        if not shape:
            results.append({"file": rel, "status": "conflict",
                            "detail": "UNKNOWN pin/package schema — shown, not written; reconcile manually"})
            continue
        bk, vk, mk = shape
        block = obj[bk]
        if vk not in block or mk not in block:
            results.append({"file": rel, "status": "conflict",
                            "detail": f"identity keys `{vk}`/`{mk}` absent in `{bk}` — shown, not written"})
            continue
        changes = []
        if block.get(vk) != want_version:
            changes.append({"key": f"{bk}.{vk}", "old": block.get(vk), "new": want_version})
        if want_manifest is not None and block.get(mk) != want_manifest:
            changes.append({"key": f"{bk}.{mk}", "old": block.get(mk), "new": want_manifest})
        # The installed kit records no verified git commit (install is keyed on version + manifest
        # digest, not a SHA). So a stale `commit` must NOT sit next to the refreshed hashes as if it
        # were current: demote it to an explicit unverified marker and keep the old SHA in history.
        # We never guess a SHA. Idempotent: once commit is null, there is nothing left to demote.
        commit_demote = ("commit" in block and block.get("commit") is not None)
        if commit_demote:
            changes.append({"key": f"{bk}.commit", "old": block.get("commit"), "new": None,
                            "reason": "UNVERIFIED_FOR_CURRENT_PACKAGE (installed kit has no commit link); "
                                      "old value preserved in commit_superseded"})
        entry = {"file": rel, "changes": changes}
        if not changes:
            entry["status"] = "match"
            results.append(entry)
            continue
        if apply:
            block[vk] = want_version
            if want_manifest is not None:
                block[mk] = want_manifest
            if commit_demote:
                block["commit_superseded"] = block["commit"]
                block["commit"] = None
                block["commit_status"] = ("UNVERIFIED_FOR_CURRENT_PACKAGE: the installed kit records no "
                                          "git commit; reconcile against a verified release commit before "
                                          "relying on it. Previous value preserved in commit_superseded.")
            p.write_text(json.dumps(obj, indent=2, ensure_ascii=False) + ("\n" if raw.endswith("\n") else ""))
            wrote = True
            entry["status"] = "updated"
        else:
            entry["status"] = "would-update"
        results.append(entry)
    if not results:
        results.append({"file": None, "status": "none",
                        "detail": "no pin/package file found in this checkout"})
    return results, wrote


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--managed-root", required=True, help="installed kit root (where kit.py installed the package)")
    ap.add_argument("--project", required=True, help="project root: a checkout OR an explicit worktree path")
    ap.add_argument("--adapter", help="project-relative (or absolute, for a worktree) path to the local adapter")
    ap.add_argument("--search-contract", help="path to the read-only search contract (e.g. .ai/project/capture-search.md)")
    ap.add_argument("--gitignore-extra", action="append", default=[], help="extra local path to gitignore (repeatable)")
    ap.add_argument("--git-root", help="git root to check tracked-status against (default: --project)")
    ap.add_argument("--reconcile-identity", action="store_true",
                    help="also reconcile stale pin/adapter/manifest identity (version + release-manifest "
                         "sha) to the installed kit; preserves history and unknown shapes. Without this "
                         "flag the pin is only reported (MISMATCH), never rewritten.")
    ap.add_argument("--apply", action="store_true", help="write changes (default: dry-run plan)")
    a = ap.parse_args(argv)

    project = Path(a.project)
    git_root = Path(a.git_root) if a.git_root else project
    report = {"actions": [], "conflicts": [], "consistency": [], "untouched": [
        "hooks", "permissions", "MCP", "credentials", "consent", "grants", "capture (not enabled)"]}

    kit = kit_identity(a.managed_root)
    if not kit["entry_rules_exists"]:
        print(json.dumps({"status": "BLOCKED", "reason": "managed root has no rules/agent-entry.md"}, indent=2))
        return 1
    report["kit"] = kit

    # resolve adapter / search references (paths only; never copy bodies or secrets)
    adapter_rel = a.adapter
    if not adapter_rel:
        for cand in (".ai/project/adapter.md", ".ai/agents/ai-factory.md", "work/rules/ai-factory.md",
                     "docs/development/ai-factory.md"):
            if (project / cand).exists():
                adapter_rel = cand
                break
    search_rel = a.search_contract
    if not search_rel:
        for cand in (".ai/project/capture-search.md", ".ai/agents/capture-search.md"):
            if (project / cand).exists():
                search_rel = cand
                break

    block_body = build_block(kit, adapter_rel, search_rel, project)

    # --- AGENTS.local.md ---
    agents_p = project / "AGENTS.local.md"
    agents_text = agents_p.read_text() if agents_p.exists() else None
    conflicts = detect_unmanaged_import(agents_text)
    for c in conflicts:
        report["conflicts"].append(f"AGENTS.local.md has an UNMANAGED kit import outside the managed block: `{c}` "
                                   "— left in place (not deleted, not duplicated); reconcile it manually.")
    agents_new, agents_action = splice_managed_block(agents_text, block_body)
    report["actions"].append({"file": "AGENTS.local.md", "action": agents_action})

    # --- CLAUDE.local.md ---
    claude_p = project / "CLAUDE.local.md"
    claude_text = claude_p.read_text() if claude_p.exists() else None
    claude_new, claude_action = ensure_claude_import(claude_text)
    report["actions"].append({"file": "CLAUDE.local.md", "action": claude_action})

    # --- .gitignore ---
    gi_p = project / ".gitignore"
    wanted = ["AGENTS.local.md", "CLAUDE.local.md"] + list(a.gitignore_extra)
    gi_existing, gi_add = gitignore_plan(gi_p, wanted)
    report["actions"].append({"file": ".gitignore", "action": ("add:" + ",".join(gi_add)) if gi_add else "noop"})
    for w in wanted:
        if git_tracked(git_root, w):
            report["conflicts"].append(f".gitignore target `{w}` is TRACKED in git — shown, not removed; "
                                       "no automatic `git rm` is run.")

    report["consistency"] = verify_consistency(project, kit)

    # Opt-in: actually reconcile stale identity fields. Conflicts/unknowns are surfaced BEFORE any
    # write so they are shown, never guessed. Writing only happens with --apply AND this flag.
    if a.reconcile_identity:
        recon, _ = reconcile_identity(project, kit, apply=a.apply)
        report["identity_reconcile"] = recon
        for r in recon:
            if r.get("status") == "conflict":
                report["conflicts"].append(
                    f"pin {r['file']}: {r['detail']}")

    if a.apply:
        if agents_action != "noop":
            agents_p.write_text(agents_new)
        if claude_action not in ("present", "noop"):
            claude_p.write_text(claude_new)
        if gi_add:
            text = ("\n".join(gi_existing).rstrip("\n") + "\n") if gi_existing else ""
            text += "\n# AI Factory local connection (machine-specific; never committed)\n" if not gi_existing or "# AI Factory local connection" not in "\n".join(gi_existing) else ""
            text += "".join(w + "\n" for w in gi_add)
            gi_p.write_text(text)
        report["status"] = "APPLIED"
    else:
        report["status"] = "PLANNED (dry-run; pass --apply to write)"

    print(json.dumps(report, indent=2, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    sys.exit(main())
